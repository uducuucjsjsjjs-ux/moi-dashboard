  const DICT = { ru, en };
  let lang = 'ru';

  function t(key, params, l) {
    const d = DICT[l || lang] || ru;
    let s = d[key];
    if (s == null) s = ru[key];
    if (s == null) return key;
    return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m)) : s;
  }

  const has = (key) => key in ru;
  function setLang(l) { lang = DICT[l] ? l : 'ru'; }
  const getLang = () => lang;

  // Подставляет переводы в разметку: data-i18n — текст, data-i18n-title — подсказка, data-i18n-ph — подпись в поле
  function apply(rootEl) {
    if (typeof document === 'undefined') return;
    const r = rootEl || document;
    r.querySelectorAll('[data-i18n]').forEach((e) => { e.textContent = t(e.getAttribute('data-i18n')); });
    r.querySelectorAll('[data-i18n-title]').forEach((e) => { e.title = t(e.getAttribute('data-i18n-title')); });
    r.querySelectorAll('[data-i18n-ph]').forEach((e) => { e.placeholder = t(e.getAttribute('data-i18n-ph')); });
    document.documentElement.lang = lang;
  }

  const api = { t, has, setLang, getLang, apply, DICT };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.I18n = api;
